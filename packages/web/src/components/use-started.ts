/**
 * Whether the page has started (`lib/after-start.ts`): false on the first
 * render and until the browser is idle, then true for good. Work behind it
 * stays off the start-up's critical path.
 */
import { useEffect, useState } from 'react';
import { afterStart } from '../lib/after-start';

export function useStarted(): boolean {
  const [started, setStarted] = useState(false);
  useEffect(() => {
    if (started) return undefined;
    return afterStart(() => setStarted(true), window);
  }, [started]);
  return started;
}
