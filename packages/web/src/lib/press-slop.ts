/**
 * Where a press stops being a click (VENT-37): past {@link PRESS_SLOP_PX}
 * it turns the globe (globe/drag.ts) and drops no pin (pin/place-press.ts).
 * One constant and one comparison, so no travel is both, or neither.
 */

/** Travel from the press, px, at which it turns the globe. */
export const PRESS_SLOP_PX = 4;

interface Point {
  readonly x: number;
  readonly y: number;
}

/** Whether a press from `from` has travelled to `to` far enough to turn. */
export function pastSlop(from: Point, to: Point): boolean {
  return Math.hypot(to.x - from.x, to.y - from.y) >= PRESS_SLOP_PX;
}
