/**
 * Ventana's own layers (VENT-37), by id and stacking order: the landing
 * sites and the approximate zones (the globe's site markers), and the
 * sites saved on this device. Another team's layer takes its own id; a z
 * over {@link LAYER_Z.saved} paints over all of these.
 */
export const LAYER_IDS = {
  sites: 'landing-sites',
  zones: 'approximate-zones',
  saved: 'saved-sites',
} as const;

export type VentanaLayer = (typeof LAYER_IDS)[keyof typeof LAYER_IDS];

export const LAYER_Z: Readonly<Record<keyof typeof LAYER_IDS, number>> = {
  zones: 10,
  sites: 20,
  saved: 30,
};
