/**
 * The visitor's language for every component of the island: the page
 * builds the translator once from its locale's catalogue and provides it
 * at the top (LunarApp).
 */
import { createContext, useContext } from 'react';
import type { I18n } from '../i18n/translate';

export const I18nContext = createContext<I18n | null>(null);

/** The translator; a component outside the provider is a bug. */
export function useI18n(): I18n {
  const i18n = useContext(I18nContext);
  if (!i18n) throw new Error('useI18n: no I18nContext provider');
  return i18n;
}
