/**
 * A number as a GLSL ES float literal (VENT-62). `${0}` gives `0`, an int
 * literal that GLSL ES 3.00 refuses where a float is wanted (`clamp(x, 0,
 * 1.0)` does not compile), so every constant a shader is built from goes
 * through here. Exponent forms (`1.46e-7`) are floats already.
 */
export function glslFloat(value: number): string {
  if (!Number.isFinite(value)) {
    throw new RangeError(`not a GLSL float: ${String(value)}`);
  }
  const text = String(value);
  return /[.e]/.test(text) ? text : `${text}.0`;
}
