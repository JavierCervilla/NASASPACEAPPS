/**
 * Puts the still in place of the start frame: every image that names a
 * `data-still` takes it, so the `<picture>` picks the still for its cut.
 * The start frames' sources already show the still under reduced motion.
 */
export function showStill(stage: ParentNode): void {
  for (const image of stage.querySelectorAll<HTMLElement>('[data-still]')) {
    const still = image.dataset.still ?? '';
    const attribute = image.tagName === 'SOURCE' ? 'srcset' : 'src';
    image.setAttribute(attribute, still);
  }
}
