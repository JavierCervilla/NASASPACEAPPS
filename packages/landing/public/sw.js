// Retires the service worker the app registered at the root before it moved under /app (VENT-109). Browsers check
// /sw.js on every visit to a page in its scope (nginx serves it no-cache), so a returning visitor installs this one,
// which unregisters itself and reloads its open pages from the network. It deletes no cache: the app's worker under
// /app/ shares this origin's caches, names its own after its build and drops the older ones when it activates.
self.addEventListener('install', () => {
  void self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      await self.registration.unregister();
      const pages = await self.clients.matchAll({ type: 'window' });
      await Promise.all(pages.map((page) => page.navigate(page.url)));
    })(),
  );
});
