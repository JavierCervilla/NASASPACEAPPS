/**
 * A long press on the pin is the start of a carry, not a request for the
 * menu: on a touch screen the browser's context menu would cut the
 * gesture (VENT-38).
 */
import type { MouseEvent } from 'react';

export function noContextMenu(event: MouseEvent): void {
  event.preventDefault();
}
