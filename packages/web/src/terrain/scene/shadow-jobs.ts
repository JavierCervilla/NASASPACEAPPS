/** Which slicer jobs touch the Sun's shadow (VENT-73, shadow-gate.ts). */

/**
 * Whether the slicer job under `key` may change what casts or receives the
 * shadow. The rings' shading (`lit:`, `far`) and the bakes (`clods:`,
 * `crater:bake`) only paint what is there; every other job builds or shows
 * geometry (a ring tile, a rock band, the crater patch and its cut-out).
 */
export function castsShadow(key: string): boolean {
  return !/^(lit:|far\d|clods:|crater:bake)/.test(key);
}
