// The emergency service worker (VENT-28): served as sw.js in place of the real one, it deletes every cache this site
// keeps, unregisters itself and reloads the open pages from the network. Procedure in docs/service-worker.md.
self.addEventListener('install', () => {
  void self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const names = await caches.keys();
      await Promise.all(names.map((name) => caches.delete(name)));
      await self.registration.unregister();
      const pages = await self.clients.matchAll({ type: 'window' });
      await Promise.all(pages.map((page) => page.navigate(page.url)));
    })(),
  );
});
