/**
 * The on-foot view's Earth map by viewport (VENT-94): a phone takes the 512 px
 * Blue Marble, anything wider the 1024 px one.
 */
import { describe, expect, it } from 'vitest';
import { earthMapUrl } from '../src/terrain/scene/surface-maps';

describe('earthMapUrl', () => {
  it('gives a phone the 512 px Earth', () => {
    expect(earthMapUrl(true)).toMatch(/on-foot-earth-512\.webp/);
  });

  it('gives a wider viewport the 1024 px Earth', () => {
    expect(earthMapUrl(false)).toMatch(/on-foot-earth\.webp/);
  });
});
