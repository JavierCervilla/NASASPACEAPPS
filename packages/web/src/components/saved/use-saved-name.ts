/**
 * The saved name of a custom point's id (VENT-37), for the views that name
 * the selected site; re-renders when the saved sites change.
 */
import { useSavedKit, useSavedSites } from './context';

export function useSavedName(): (id: string) => string | undefined {
  const sites = useSavedSites(useSavedKit());
  return (id) => sites.find((site) => site.id === id)?.name;
}
