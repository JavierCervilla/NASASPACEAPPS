/**
 * A Three.js geometry over pure buffers (shapes.ts, tile-mesh.ts): the one
 * place the scene turns transferable arrays into GPU geometry.
 */
import { BufferAttribute, BufferGeometry } from 'three';
import type { MeshBuffers } from '../shapes';

/** The geometry of `buffers`. */
export function geometryOf(buffers: MeshBuffers): BufferGeometry {
  const geometry = new BufferGeometry();
  geometry.setAttribute('position', new BufferAttribute(buffers.positions, 3));
  geometry.setAttribute('normal', new BufferAttribute(buffers.normals, 3));
  geometry.setIndex(new BufferAttribute(buffers.index, 1));
  return geometry;
}
