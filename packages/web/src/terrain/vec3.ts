/** The little vector arithmetic the scene's pure modules share. */
import type { Vec3 } from './view-camera';

export const dot = (a: Vec3, b: Vec3): number =>
  a[0] * b[0] + a[1] * b[1] + a[2] * b[2];

export const cross = (a: Vec3, b: Vec3): Vec3 => [a[1] * b[2] - a[2] * b[1],
  a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];

/** `a * x + b * y`. */
export const mix = (a: Vec3, x: number, b: Vec3, y: number): Vec3 =>
  [a[0] * x + b[0] * y, a[1] * x + b[1] * y, a[2] * x + b[2] * y];

/** `a` scaled to unit length. */
export const unit = (a: Vec3): Vec3 =>
  mix(a, 1 / (Math.hypot(...a) || 1), a, 0);
