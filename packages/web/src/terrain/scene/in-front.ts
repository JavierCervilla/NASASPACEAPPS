/**
 * Whether a point lies in front of the camera, read in the camera's own
 * space. The projected z cannot tell it once the depth is reversed
 * (VENT-103: three's reversedDepthBuffer maps a point behind the eye to a z
 * under 1), so the labels and the bodies' marks ask this instead.
 */
import type { Camera, Vector3 } from 'three';

/** Whether `point` is ahead of `camera`, which looks down its own -z. */
export function inFront(camera: Camera, point: Vector3): boolean {
  return point.clone().applyMatrix4(camera.matrixWorldInverse).z < 0;
}
