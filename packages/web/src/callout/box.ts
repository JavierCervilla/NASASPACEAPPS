/** Boxes on screen, in px from the globe host's top left. Pure. */

export interface Box {
  readonly left: number;
  readonly top: number;
  readonly right: number;
  readonly bottom: number;
}

export interface Point {
  readonly x: number;
  readonly y: number;
}

/** The area two boxes share, in px²; 0 when they do not touch. */
export function overlap(a: Box, b: Box): number {
  const width = Math.min(a.right, b.right) - Math.max(a.left, b.left);
  const height = Math.min(a.bottom, b.bottom) - Math.max(a.top, b.top);
  return width > 0 && height > 0 ? width * height : 0;
}

/** How many px² of `box` fall outside `area`. */
export function overflow(box: Box, area: Box): number {
  const size = (b: Box): number => (b.right - b.left) * (b.bottom - b.top);
  return size(box) - overlap(box, area);
}

/**
 * `box` slid into `area`, keeping its size; when it is larger than the
 * area its top left wins.
 */
export function clampInto(box: Box, area: Box): Box {
  const shift = (low: number, high: number): number =>
    Math.max(low, Math.min(0, high));
  const dx = shift(area.left - box.left, area.right - box.right);
  const dy = shift(area.top - box.top, area.bottom - box.bottom);
  return {
    left: box.left + dx,
    top: box.top + dy,
    right: box.right + dx,
    bottom: box.bottom + dy,
  };
}

/** Whether `point` lies inside `area` (edges included). */
export function holds(area: Box, point: Point): boolean {
  const { x, y } = point;
  return x >= area.left && x <= area.right && y >= area.top && y <= area.bottom;
}
