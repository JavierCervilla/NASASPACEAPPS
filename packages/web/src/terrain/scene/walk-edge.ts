/**
 * When the reach's edge card shows (VENT-121, VENT-128): the eye stands
 * held to the reach, not on its way anywhere, so the card goes as soon as
 * a glide starts («Back», or another tap) and comes back only if the eye
 * arrives at the edge again.
 */
import type { ViewState } from './scene-frame';

/** Whether the edge card shows for `view`. */
export const edgeShown = (view: ViewState): boolean =>
  view.edge && view.glide === null;
