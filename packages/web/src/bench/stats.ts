/**
 * The benchmark's statistics (VENT-81): median, nearest-rank percentile
 * and worst of a list of numbers, and the frame summary of a step. Pure.
 */
import type { FrameStats } from './types';

/** The nearest-rank `p`th percentile (0 to 100) of `values`; null if none. */
export function percentile(
  values: readonly number[],
  p: number,
): number | null {
  if (values.length === 0) return null;
  const sorted = [...values].sort((a, b) => a - b);
  const rank = Math.ceil((p / 100) * sorted.length);
  return sorted[Math.min(Math.max(rank, 1), sorted.length) - 1] ?? null;
}

/** The median of `values` (the mean of the middle two); null if none. */
export function median(values: readonly number[]): number | null {
  if (values.length === 0) return null;
  const sorted = [...values].sort((a, b) => a - b);
  const mid = Math.floor(sorted.length / 2);
  const upper = sorted[mid] ?? 0;
  if (sorted.length % 2 === 1) return upper;
  return ((sorted[mid - 1] ?? 0) + upper) / 2;
}

/** The frame summary of a step's frame intervals, ms. */
export function frameStats(intervals: readonly number[]): FrameStats {
  const mid = median(intervals);
  return {
    fps: mid === null || mid <= 0 ? null : 1000 / mid,
    p95Ms: percentile(intervals, 95),
    worstMs: intervals.length === 0 ? null : Math.max(...intervals),
    drawn: intervals.length,
  };
}
