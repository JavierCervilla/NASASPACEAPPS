import type { Locale } from '../i18n/locales';

/** Degrees to one decimal, in the page's language. */
export function degrees(locale: Locale): Intl.NumberFormat {
  return new Intl.NumberFormat(locale, { maximumFractionDigits: 1 });
}

/** «Sun 22 Nov, 20:00 UTC» in the page's language. */
export function instantText(ms: number, locale: Locale): string {
  return new Intl.DateTimeFormat(locale, {
    weekday: 'short',
    day: 'numeric',
    month: 'short',
    hour: '2-digit',
    minute: '2-digit',
    hourCycle: 'h23',
    timeZone: 'UTC',
    timeZoneName: 'short',
  }).format(ms);
}

/** «November 2026» in the page's language. */
export function monthText(ms: number, locale: Locale): string {
  return new Intl.DateTimeFormat(locale, {
    month: 'long',
    year: 'numeric',
    timeZone: 'UTC',
  }).format(ms);
}

/** A share as a whole percentage, «48 %». */
export function percentText(share: number, locale: Locale): string {
  return new Intl.NumberFormat(locale, {
    style: 'percent',
    maximumFractionDigits: 0,
  }).format(share);
}
