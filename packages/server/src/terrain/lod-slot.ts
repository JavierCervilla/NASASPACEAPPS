/**
 * The client's slot around a levelled tile's computation (VENT-46): taken
 * before the work, given back after it, whatever happens.
 */

/** Takes a client slot; the function it resolves to gives it back. */
export type SlotTaker = () => Promise<() => void>;

/**
 * Runs `work` holding a client slot (taken first, which may wait or refuse),
 * and gives the slot back however `work` ends.
 */
export async function underSlot<T>(
  work: () => Promise<T>,
  slot?: SlotTaker,
): Promise<T> {
  const release = await slot?.();
  try {
    return await work();
  } finally {
    release?.();
  }
}
