/**
 * Tells whether the hero is worth playing: some of it on screen and the
 * page shown. Called once the observer first reports.
 */
export function watchShown(
  target: Element,
  onShown: (shown: boolean) => void,
): void {
  const doc = target.ownerDocument;
  let onScreen = false;
  const tell = () =>
    onShown(onScreen && doc.visibilityState === 'visible');
  new IntersectionObserver((entries) => {
    onScreen = entries.some((entry) => entry.isIntersecting);
    tell();
  }).observe(target);
  doc.addEventListener('visibilitychange', tell);
}
