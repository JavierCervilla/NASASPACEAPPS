/**
 * The hours of one UTC month out of a longer run: the API answers the
 * month and the 30 days after it, and the calendar's bars and the site
 * card's figures count the month alone. Pure.
 */
import { toIso, type HourSample } from '@ventana/sim';
import { samplesWithin } from '../phone/site-widgets';
import { monthEndMs, monthStartMs } from './month';

/** The samples of `hours` inside the UTC month of `atMs`. */
export function monthSamples(
  hours: readonly HourSample[],
  atMs: number,
): HourSample[] {
  const first = toIso(monthStartMs(atMs));
  return samplesWithin(hours, first, toIso(monthEndMs(atMs)));
}
