/**
 * The scene's loop, shut until its programs are compiled (VENT-69): a frame
 * asked for before is not lost, the first one is drawn when the gate opens.
 */
import type { Loop } from '../../globe/loop';

/** A loop that draws nothing until it is opened. */
export function gateLoop(loop: Loop): Loop & { readonly open: () => void } {
  let opened = false;
  return {
    invalidate: () => {
      if (opened) loop.invalidate();
    },
    stop: () => loop.stop(),
    open: () => {
      opened = true;
      loop.invalidate();
    },
  };
}
