/**
 * The astronaut's dock on phones (VENT-10, validated canvas «Astro A
 * phone»): a round glass button beside the tab bar, in the thumb's reach.
 * It works like the desktop one (use-dock.ts); its words are its name.
 */
import { Figure } from './Figure';
import { useDock } from './use-dock';

export function PhoneDock() {
  const { status, label, ...handlers } = useDock();
  return (
    <button
      type="button"
      className="astro-phone-dock"
      data-status={status}
      aria-label={label}
      {...handlers}
    >
      <span className="astro-dock__spot">
        {status === 'home' ? <Figure pose="stand" visor="idle" /> : null}
      </span>
    </button>
  );
}
