/**
 * The globe's quality settings (VENT-93): the ones the boot read before
 * the globe's chunk loaded (start-maps.ts), so the mount makes no second
 * probe, else the page's pick now.
 */
import type { QualitySettings } from '../lib/quality';
import { isPhoneViewport } from '../lib/viewport';
import { pickQuality } from './quality-pick';

export const globeQuality = (
  early?: { readonly quality: QualitySettings } | undefined,
): QualitySettings => early?.quality ?? pickQuality(isPhoneViewport());
