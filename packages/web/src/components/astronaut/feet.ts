/**
 * Where a figure stands: the middle of its picture's bottom edge, a
 * twentieth up (the pictures' feet, astronaut/figure-types.ts).
 */
import { PICTURE } from '../../astronaut/figure-types';
import type { ClientPoint } from '../../astronaut/surfaces';

export function feetOf(el: Element | null): ClientPoint {
  const box = el?.getBoundingClientRect();
  if (!box) return { x: 0, y: 0 };
  const y = box.top + box.height * PICTURE.feetY;
  return { x: box.left + box.width * PICTURE.feetX, y };
}
