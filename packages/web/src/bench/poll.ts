/**
 * Polling a condition for the benchmark (VENT-81): checked every
 * {@link POLL_MS} on the injected sleep until it holds or the time is up.
 */

const POLL_MS = 100;

export type Sleep = (ms: number) => Promise<void>;

/** Polls `test` until true or `timeoutMs`; false on the timeout. */
export async function until(
  test: () => boolean,
  timeoutMs: number,
  sleep: Sleep,
): Promise<boolean> {
  const end = performance.now() + timeoutMs;
  while (!test()) {
    if (performance.now() >= end) return false;
    await sleep(POLL_MS);
  }
  return true;
}
