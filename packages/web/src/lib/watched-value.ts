/**
 * A value one part of the page sets and another follows, passed to both so
 * there is no module-level state: the phone sheet's top edge, which the
 * globe needs to keep its label in view.
 */

export interface WatchedValue<T> {
  get(): T;
  /** Sets the value; listeners run only when it changes. */
  set(value: T): void;
  /** Calls `listener` after every change; returns the unsubscribe. */
  subscribe(listener: () => void): () => void;
}

/** A watched value that starts at `initial`. */
export function createWatchedValue<T>(initial: T): WatchedValue<T> {
  let current = initial;
  const listeners = new Set<() => void>();
  return {
    get: () => current,
    set: (value) => {
      if (Object.is(value, current)) return;
      current = value;
      for (const listener of [...listeners]) listener();
    },
    subscribe: (listener) => {
      listeners.add(listener);
      return () => void listeners.delete(listener);
    },
  };
}
