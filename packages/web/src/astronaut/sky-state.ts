/**
 * The state at one instant of any point, from the simulator's sky
 * (`skyAt`): what the astronaut's readout and visor show while it is
 * carried, every move, without a month of hours. Pure.
 */
import { skyAt } from '@ventana/sim';
import type { LatLon } from '../lib/polar-projection';
import { nowState } from '../phone/now-widget';
import type { NowState } from '../phone/widget-types';

/** Sun and Earth over `point` at `ms`: window, one of them, or none. */
export function stateAtPoint(point: LatLon, ms: number): NowState {
  const sky = skyAt({ latDeg: point.lat, lonEastDeg: point.lonEast }, ms);
  return nowState(sky);
}
