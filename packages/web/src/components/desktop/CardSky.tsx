import type { ReactNode } from 'react';
import { ListeningBlock, ListeningWaiting } from '../dsn/ListeningBlock';
import type { Dsn } from '../dsn/use-dsn';

interface Props {
  /** The site's horizon strip; null in the Horizon view. */
  readonly horizon: ReactNode;
  /** The DSN at the instant; null until it is worked out. */
  readonly dsn: Dsn | null;
}

export function CardSky({ horizon, dsn }: Props) {
  return (
    <div className="card-block card-sky">
      {horizon}
      {dsn ? <ListeningBlock dsn={dsn} /> : <ListeningWaiting />}
    </div>
  );
}
