import type { FilmVideo } from './film-player';

/** A `<video>` as the player sees it: sources go in only when asked. */
export function videoOf(video: HTMLVideoElement): FilmVideo {
  return {
    load(sources) {
      video.muted = true;
      video.preload = 'auto';
      video.replaceChildren(
        ...sources.map(({ src, type }) => {
          const element = video.ownerDocument.createElement('source');
          Object.assign(element, { src, type });
          return element;
        }),
      );
      video.load();
    },
    play: () => video.play(),
    pause: () => video.pause(),
    on: (event, listener) => video.addEventListener(event, listener),
  };
}
