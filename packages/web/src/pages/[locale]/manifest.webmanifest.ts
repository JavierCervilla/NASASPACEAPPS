/**
 * The manifest of every other offered locale, in its own folder:
 * /es/manifest.webmanifest… The pseudo-locale is never installable.
 */
import type { APIRoute, GetStaticPaths } from 'astro';
import { DEFAULT_LOCALE, LOCALES, type Locale } from '../../i18n/locales';
import { manifestResponse } from '../../pwa/manifest-route';

export const getStaticPaths = (() =>
  LOCALES.filter((l) => l !== DEFAULT_LOCALE).map((locale) => ({
    params: { locale },
    props: { locale },
  }))) satisfies GetStaticPaths;

export const GET: APIRoute<{ locale: Locale }> = ({ props }) =>
  manifestResponse(props.locale, import.meta.env.BASE_URL);
