/**
 * The listed site the selection falls back to when the astronaut goes
 * home (VENT-10): the last one chosen, never the custom point.
 */
import type { SiteStore } from '../phone/site-store';
import { customPointOf } from './custom-point';

/** Follows `store`; returns the last listed site and how to stop. */
export function followListed(store: SiteStore) {
  let listed = store.get().id;
  const stop = store.subscribe(() => {
    const { id } = store.get();
    if (!customPointOf(id)) listed = id;
  });
  return { get: (): string => listed, stop };
}
