import { computedHours, terrainHours, type HourSample } from '@ventana/sim';
import { sitePoint, siteProfile } from './site';

const point = sitePoint();
const profile = siteProfile();

/**
 * IM-2's hours from `fromIso` to `lastIso`, both included: the simulator's
 * sky (within 0.05° of JPL Horizons, VENT-36) read against the site's LOLA
 * horizon, as the app shows them before Horizons answers.
 */
export function siteHours(fromIso: string, lastIso: string): HourSample[] {
  return [...terrainHours(computedHours(point, fromIso, lastIso), profile)];
}
