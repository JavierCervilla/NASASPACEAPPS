/**
 * The one choice of the loader's picture (VENT-60), keyed by the view's
 * tier: the plan of the near tiles, then the skyline (B→A, the human's
 * verdict), on every tier today. A picture for one tier plugs in here.
 */
import type { Tier } from '../../lib/quality';

export type LoaderPicture = 'tilesThenSkyline';

const PICTURES: Readonly<Record<Tier, LoaderPicture>> = {
  low: 'tilesThenSkyline',
  medium: 'tilesThenSkyline',
  high: 'tilesThenSkyline',
};

/** The loader's picture at `tier`. */
export const loaderPicture = (tier: Tier): LoaderPicture => PICTURES[tier];
