/** Event listeners added together and taken off together. */

type Listener = (event: Event) => void;

export function listenerSet() {
  const added: [EventTarget, string, Listener][] = [];
  return {
    on: (target: EventTarget, type: string, fn: Listener): void => {
      added.push([target, type, fn]);
      target.addEventListener(type, fn);
    },
    off: (): void => {
      for (const [target, type, fn] of added) {
        target.removeEventListener(type, fn);
      }
    },
  };
}
