/**
 * The keys of a menu list (WAI-ARIA menu pattern): the arrows move
 * through its items and wrap, Home and End reach its ends. Pure.
 */

/**
 * The item `key` moves the focus to, from item `at` of `count` (-1: none
 * has it); null for a key the menu does not use.
 */
export function menuIndex(key: string, at: number, count: number) {
  if (count === 0) return null;
  if (key === 'ArrowDown') return (at + 1) % count;
  if (key === 'ArrowUp') return at <= 0 ? count - 1 : at - 1;
  if (key === 'Home') return 0;
  return key === 'End' ? count - 1 : null;
}
