/** The app's views, by the hash that opens each (the app's view-tabs.ts). */
export const APP_VIEWS = ['#globe', '#polar-map', '#dsn', '#horizon'];

/**
 * Where an old link to one of the app's views goes now that the app lives
 * under /app (VENT-109): the browser never sends the hash, so nginx cannot
 * redirect `/#horizon`. Null for any other hash, which stays on the landing.
 */
export function appHashTarget(hash: string, appRoot: string): string | null {
  return APP_VIEWS.includes(hash) ? `${appRoot}${hash}` : null;
}
