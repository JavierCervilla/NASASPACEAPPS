/**
 * Keeps a live instant on the clock: at the top of each hour, and when a
 * hidden page comes back in a later hour (phone/hour-clock.ts). The data
 * is hourly, so nothing finer is worth a re-render. A chosen instant is
 * left alone.
 */
import { watchHour, type HourClockDeps } from '../phone/hour-clock';
import type { TimeStore } from './time-store';

/** Starts following; returns the function that stops it. */
export function followClock(
  store: TimeStore,
  clock: HourClockDeps,
): () => void {
  return watchHour(clock, () => {
    if (store.get().live) store.now();
  });
}
