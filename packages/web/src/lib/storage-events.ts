/**
 * Another tab changed the device's storage: the browser tells every other
 * tab with a `storage` event naming the key (none when it was cleared).
 * Lists and flags kept there (VENT-37) read it again on that.
 */

/** Calls `fn` when another tab changes `key` (or clears all); unsubscribe. */
export function onStorageKey(
  target: Pick<EventTarget, 'addEventListener' | 'removeEventListener'>,
  key: string,
  fn: () => void,
): () => void {
  const listener = (event: Event): void => {
    const changed = (event as StorageEvent).key;
    if (changed === key || changed === null) fn();
  };
  target.addEventListener('storage', listener);
  return () => target.removeEventListener('storage', listener);
}
