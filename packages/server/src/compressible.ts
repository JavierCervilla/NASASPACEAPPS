/**
 * Which answers the API compresses: Hono's list of compressible types
 * (JSON, text…) and the binary terrain tiles (VENT-98), whose predicted
 * heights gzip to about a third. Hono leaves `application/octet-stream` out
 * because it is usually already compressed; ours is not.
 */
import { COMPRESSIBLE_CONTENT_TYPE_REGEX } from 'hono/compress';

const BINARY_TILE = /^\s*application\/octet-stream(?:[;\s]|$)/i;

/** True when an answer of `contentType` is worth compressing. */
export function compressible(contentType: string): boolean {
  return COMPRESSIBLE_CONTENT_TYPE_REGEX.test(contentType)
    || BINARY_TILE.test(contentType);
}
