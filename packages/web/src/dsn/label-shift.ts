/**
 * How far a label centred on a picture point must move sideways to stay
 * inside the picture (VENT-7): at 200 % text a label by an antenna near
 * the limb ran past the phone's edge. One too wide for the picture
 * starts at its left edge, so its first words show.
 */

/**
 * The sideways shift, in px, that keeps a label of `width` whose left
 * edge sits at `left` (px from the picture's left) inside `span` px.
 */
export function labelShift(left: number, width: number, span: number) {
  if (left < 0 || width >= span) return -left;
  const over = left + width - span;
  return over > 0 ? -over : 0;
}
