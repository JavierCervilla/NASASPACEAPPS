/**
 * The sha256 of a stream of chunks (VENT-44), checked against a signal
 * between chunks: hashing a tier file of gigabytes takes longer than the
 * shutdown's grace time, and a stop must still let go of the volume's
 * lock before the process exits.
 */
import { createHash } from 'node:crypto';

/** The hex sha256 of `chunks`; throws the abort reason once aborted. */
export async function sha256Of(
  chunks: AsyncIterable<Uint8Array>,
  signal?: AbortSignal,
): Promise<string> {
  const hash = createHash('sha256');
  signal?.throwIfAborted();
  for await (const chunk of chunks) {
    signal?.throwIfAborted();
    hash.update(chunk);
  }
  return hash.digest('hex');
}
