/** Translators for the tests: English, and any locale on demand. */
import { CATALOGUES, catalogueOf } from '../src/i18n/catalogues';
import type { UiLocale } from '../src/i18n/locales';
import { createI18n, type I18n } from '../src/i18n/translate';

/** The English translator, which the wording tests read. */
export const EN: I18n = createI18n('en', CATALOGUES.en);

/** The translator of `locale`. */
export const i18nOf = (locale: UiLocale): I18n => createI18n(locale, catalogueOf(locale));
