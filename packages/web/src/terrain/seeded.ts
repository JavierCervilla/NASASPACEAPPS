/**
 * The seeded randomness of the illustrative detail (VENT-34): one seed
 * per point on the server's 0.01° grid, so a place always shows the same
 * rocks and grain, and a small generator from it. Cosmetic only: nothing
 * measured comes from here. Pure.
 */
import type { LatLon } from '../lib/polar-projection';

const GRID = 100;

/** A 32-bit seed for `point`, on the 0.01° grid. */
export function seedOf({ lat, lonEast }: LatLon): number {
  let h = Math.imul(Math.round(lat * GRID), 374_761_393);
  h = (h + Math.imul(Math.round(lonEast * GRID), 668_265_263)) | 0;
  h = Math.imul(h ^ (h >>> 13), 1_274_126_177);
  return (h ^ (h >>> 16)) >>> 0;
}

/** Numbers from 0 (included) to 1, the same run for the same seed. */
export function generator(seed: number): () => number {
  let state = seed | 0;
  return () => {
    state = (state + 0x6d2b79f5) | 0;
    let t = Math.imul(state ^ (state >>> 15), 1 | state);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4_294_967_296;
  };
}
