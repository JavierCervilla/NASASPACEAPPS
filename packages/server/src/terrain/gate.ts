/**
 * A cap on concurrent horizon computations (VENT-40), as the Horizons
 * client caps its downloads: each holds its blocks in memory while it
 * runs, so a burst waits in a short queue, and past it is refused.
 */

/** The queue is full: the caller should try again later. */
export class TerrainBusyError extends Error {
  override readonly name = 'TerrainBusyError';
}

export class Gate {
  private running = 0;
  private readonly waiting: (() => void)[] = [];
  private readonly maxRunning: number;
  private readonly maxWaiting: number;

  constructor(maxRunning: number, maxWaiting: number) {
    this.maxRunning = maxRunning;
    this.maxWaiting = maxWaiting;
  }

  /** Runs `task` when a slot is free; throws when the queue is full. */
  async run<T>(task: () => Promise<T>): Promise<T> {
    if (this.running >= this.maxRunning) {
      if (this.waiting.length >= this.maxWaiting) throw new TerrainBusyError();
      await new Promise<void>((resolve) => this.waiting.push(resolve));
    } else this.running++;
    try {
      return await task();
    } finally {
      const next = this.waiting.shift();
      if (next) next();
      else this.running--;
    }
  }
}
