/**
 * The end card's placeholder backdrop: one frame of the raea 3D Moon (the
 * Earth over the horizon), without type, until the hero film's hold frame
 * (VENT-112) replaces it (END_BACKDROP in scenes/plates.ts).
 *
 *   raea render backdrop.tsx -o media/plates/end-backdrop-placeholder.png --frame 0
 */
import { Composition, registerRoot } from "raea";
import { MoonShot } from "./scenes/shots";

/** The Earth-setting shot near its start, the Earth well above the horizon. */
function Backdrop() {
  return <MoonShot name="earthset" frames={10} />;
}

registerRoot(() => <Composition id="end-backdrop" component={Backdrop} width={1920} height={1080} fps={30} durationInFrames={1} />);
